"""LLM protocol definitions: the interface every client must satisfy, plus shared exception types and utilities."""

import re
from dataclasses import dataclass
from typing import Protocol


class LLMError(RuntimeError):
    """Unified exception type raised when an LLM call or response-parse fails."""


@dataclass
class ToolCall:
    """A single tool invocation requested by the LLM, executed by the runtime."""

    tool_id: str                  # call id generated by the LLM, used to pair with a result
    tool_name: str
    arguments: dict


@dataclass
class ToolResult:
    """Tool execution result, paired with a ToolCall by tool_id."""

    tool_id: str
    tool_name: str
    output: str                   # JSON-serialized tool output
    is_error: bool = False


class LLMClient(Protocol):
    """Structural subtype protocol every LLM client must satisfy."""

    model: str  # current model identifier

    def call(
        self, *, system: str, user: str, cache_system: bool = False
    ) -> tuple[str, dict]:
        """Send a chat request and return (response text, token-usage dict)."""
        ...

    def call_json(
        self, *, system: str, user: str, cache_system: bool = False
    ) -> tuple[dict, dict]:
        """Send a chat request and parse the response as JSON; return (parsed dict, token-usage dict)."""
        ...

    def call_with_tools(
        self, *, system: str, user: str,
        tools: list[dict],
        previous_messages: list[dict] | None = None,
    ) -> tuple[str | None, list[ToolCall], dict]:
        """Single-round tool-use call. Returns (final_text or None, tool_calls, usage).

        - tool_calls non-empty -> the runtime executes them and feeds the
          results into the next round.
        - tool_calls empty and final_text non-empty -> the agent is done
          and final_text is the answer.
        """
        ...


# Match a code fence with any language tag (```python / ```json / ``` etc.), spanning lines.
# \w* swallows the language tag; the following \s* swallows the newline
# between tag and content so the tag does not leak into the body.
_FENCE_RE = re.compile(r"```\w*\s*(.+?)\s*```", re.DOTALL)


def strip_code_fences(text: str) -> str:
    """Strip the optional code-fence wrapper from LLM output (```python / ```json / ``` all supported).

    Returns the fence contents (language tag removed) when a fence is
    found, otherwise the original text stripped of surrounding whitespace.
    """
    m = _FENCE_RE.search(text)
    return m.group(1) if m else text.strip()


def _escape_inner_string_chars(text: str) -> str:
    r"""Scan the text once with a state machine and escape illegal characters inside JSON string values:
      - Unescaped `"` -> `\"` (the LLM embedding English quotation, e.g.
        `"X or not Y"`).
      - Literal newlines `\n` / `\r` / tabs `\t` -> `\\n` / `\\r` / `\\t`
        (when the LLM emits multi-line feedback or embeds ```code```
        blocks it often prints real newlines, but JSON forbids literal
        control characters inside strings).

    Whether a `"` is a real string close is decided by looking at the
    first non-whitespace character after it: if that character is a JSON
    structural character `, } ] :` or EOF, the quote closes the string;
    otherwise it is an embedded quote and gets escaped. The heuristic is
    conservative and imperfect (nested cases can be misclassified) but
    handles common LLM mistakes — including the "glm-5.1 embeds
    ```python ...``` code blocks inside feedback" case.
    """
    out: list[str] = []
    i = 0
    n = len(text)
    in_string = False
    while i < n:
        c = text[i]
        if not in_string:
            out.append(c)
            if c == '"':
                in_string = True
            i += 1
            continue
        # inside a string
        if c == "\\" and i + 1 < n:
            out.append(c)
            out.append(text[i + 1])
            i += 2
            continue
        if c == '"':
            j = i + 1
            while j < n and text[j] in " \t\n\r":
                j += 1
            next_c = text[j] if j < n else ""
            if next_c in ",}]:" or next_c == "":
                out.append(c)
                in_string = False
                i += 1
            else:
                # embedded unescaped quote -> insert escape
                out.append("\\")
                out.append('"')
                i += 1
            continue
        # literal control char -> emit the corresponding JSON escape
        if c == "\n":
            out.append("\\")
            out.append("n")
            i += 1
            continue
        if c == "\r":
            out.append("\\")
            out.append("r")
            i += 1
            continue
        if c == "\t":
            out.append("\\")
            out.append("t")
            i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


# Backwards-compatible alias for the old API (tests / external references, if any).
_escape_inner_quotes = _escape_inner_string_chars


def _balance_brackets(text: str) -> str:
    """Count unclosed `{` / `[` outside any string and append matching `}` / `]` in LIFO order.

    A single pass tracks `in_string` / `escape` state and only pushes
    `{` / `[` and pops on `}` / `]` while outside a string. If the stack
    is still non-empty at the end, append the matching closers in
    reverse-push order.

    Purpose: Opus 4.7 / GLM / DeepSeek occasionally drop the outer
    `}` / `]` when emitting JSON (~1% in practice). This handles that
    specific structural failure. The patched text is still parsed by
    `json.loads`, so a wrong patch still raises — we never silently emit
    an incorrect structure.
    """
    stack: list[str] = []
    in_string = False
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if in_string:
            if c == "\\" and i + 1 < n:
                i += 2
                continue
            if c == '"':
                in_string = False
            i += 1
            continue
        if c == '"':
            in_string = True
        elif c == "{":
            stack.append("}")
        elif c == "[":
            stack.append("]")
        elif c in "}]" and stack and stack[-1] == c:
            stack.pop()
        i += 1
    if not stack:
        return text
    return text + "".join(reversed(stack))


def try_parse_json_tolerant(text: str):
    """Try strict json.loads first; on failure apply escalating tolerant sanitizations.

    Sanitization levels (from lightest to heaviest):
      1) Full-width punctuation: `，` -> `,`, `：` -> `:` (a common
         mistake when the LLM is in a Chinese context and types
         full-width separators inside JSON).
      2) Escape illegal characters inside strings: unescaped `"`,
         literal newlines `\\n` / `\\r` / tabs (LLM long feedback or
         embedded ```code``` blocks emit real newlines, which JSON
         forbids inside string values).
      3) Missing trailing brackets: count unclosed `{` / `[` outside any
         string and append matching closers in stack order (Opus 4.7 /
         GLM occasionally drop the trailing `}`).

    Returns the parsed value (dict / list) on success; raises
    json.JSONDecodeError when every level still fails.
    """
    import json
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    # Level 1: full-width punctuation.
    sanitized = text.replace("，", ",").replace("：", ":")
    try:
        return json.loads(sanitized)
    except json.JSONDecodeError:
        pass
    # Level 2: escape illegal chars inside strings (quote / newline / tab / CR).
    sanitized2 = _escape_inner_string_chars(sanitized)
    try:
        return json.loads(sanitized2)
    except json.JSONDecodeError:
        pass
    # Level 3: missing trailing brackets -> auto-append matching closers.
    balanced = _balance_brackets(sanitized2)
    if balanced != sanitized2:
        # If parsing still fails after balancing, the structure has a
        # deeper problem than a missing tail; raise the balanced text's
        # error to preserve diagnostic detail.
        return json.loads(balanced)
    # Brackets balanced already but parse still failed -> raise the original error from sanitized2.
    return json.loads(sanitized2)
